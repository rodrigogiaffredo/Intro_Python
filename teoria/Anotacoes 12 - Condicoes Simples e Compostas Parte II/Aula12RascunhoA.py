# chamadas de condições aninhadas.

# Sintaxe genérica: if..: elif..: else..:

# A instrução elif..: equivale a um else if, ou seja, um else que não encerra a conversa, mas
# propõe uma outra possibilidade (tipo, se, senão se, senão).

