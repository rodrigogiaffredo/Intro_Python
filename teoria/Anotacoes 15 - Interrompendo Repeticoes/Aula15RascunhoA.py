# Repetições WHILE (com teste lógico no início) podem ser interrompidas. Essa interrupção
# desvia o programa para o lado de fora do laço de repetição, eliminando inclusive a
# necessidade do teste lógico no início do programa.

# Sintaxe:      while true
#                   if condição
#                        comando
#                   if condição
#                        comando
#                   if condição
#                        comando
#                   if condição
#                        comando
#                        break
#               comando

# Dessa forma, o loop acontecerá infinitamente, até que a condição que aciona o break ocorra.
# Nesse momento, ao invés de o programa retornar para o gatilho do loop, ele sairá do laço e
# passará a executar os comandos fora dele.


