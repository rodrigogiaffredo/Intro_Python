# OBJETOS são VARIÁVEIS EVOLUÍDAS

# VALE MUITO A PENA ASSISTIR ESSE VÍDEO: https://youtu.be/OemVdsibSFQ?si=6E6pUgisOKtYz2gF

# O auge das variáveis está nos dicionários, que permitem uma indexação literal de seus
# conteúdos, além de aceitarem simultâneamente diferentes tipos de dados.

# Porém eles não resolvem a questão da separação entre dados e funções. Os dicionários vão
# armazenar os dados, e as funções precisam ser criadas em paralelo (se poucas no próprio
# programa; se muitas em módulos e pacotes).

# Objetos resolvem esse ponto: agregam dados e as funções que agem nesses dados, como se
# fossem uma super variável.

# Evoluindo a definição anterior dada a objetos:

# OBJETO: É UMA VARIÁVEL QUE, ALÉM DE GUARDAR DADOS, PODE EXECUTAR FUNCIONALIDADES.

# Particularmente em Python, qualquer variável é um objeto de alguma classe (string,
# int, float, bool), mas nem toda linguagem funciona assim, daí a importância de saber
# as definições e conceitos.