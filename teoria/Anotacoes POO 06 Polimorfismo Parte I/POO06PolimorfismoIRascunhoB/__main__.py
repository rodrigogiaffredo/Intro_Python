
# Polimorfismo aplicado no contexto de Function Overload

# Função len() retornando total de caracteres
print(len('Rodrigo Giaffredo'))
# Função len() retornando total de itens - dados - da lista
print(len(['Curso', 'Python']))
# Função len() retornando total de itens - combinação chaves + dados - do dicionário
print(len({'nome':'Maria', 'idade':22}))


# Polimorfismo aplicado no contexto de Operator Overload

# Operador '+' tipificando um número - positivo ou negativo
print(+12)
# Operador '+' efetuando uma soma
print(5.5 + 2.2)
# Operador '+' concatenando strings
print('Poli' + 'morfismo')
# Operador '+' unindo duas listas em uma
print([1, 3, 4] + [9, 7])


